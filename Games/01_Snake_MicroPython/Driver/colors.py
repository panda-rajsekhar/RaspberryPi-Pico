"""
=================================================
colors.py
RGB565 Color Definitions for ST7735 Displays
=================================================
"""

# -------------------------------------------------
# Basic Colors
# -------------------------------------------------

BLACK   = 0x0000
WHITE   = 0xFFFF

RED     = 0xF800
GREEN   = 0x07E0
BLUE    = 0x001F

# -------------------------------------------------
# Secondary Colors
# -------------------------------------------------

YELLOW  = 0xFFE0
CYAN    = 0x07FF
AQUA    = CYAN

MAGENTA = 0xF81F

# -------------------------------------------------
# Shades
# -------------------------------------------------

GRAY        = 0x8410
LIGHTGRAY   = 0xC618
DARKGRAY    = 0x4208

# -------------------------------------------------
# Warm Colors
# -------------------------------------------------

ORANGE      = 0xFD20
PINK        = 0xFC18
PURPLE      = 0x780F
BROWN       = 0xA145

# -------------------------------------------------
# Dark Colors
# -------------------------------------------------

NAVY        = 0x000F
MAROON      = 0x8000
OLIVE       = 0x8400
TEAL        = 0x0410